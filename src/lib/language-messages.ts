export type TranslationKey = keyof (typeof messages)["uk"];

export function translate(
  locale: AppLocale,
  key: TranslationKey,
  values?: Record<string, string | number>,
): string {
  const template = messages[locale][key] as string;
  return values
    ? template.replace(/\{(\w+)\}/g, (_, name: string) =>
        String(values[name] ?? ""),
      )
    : template;
}

