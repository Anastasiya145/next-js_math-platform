ALTER TABLE students
  ADD COLUMN IF NOT EXISTS language_level TEXT
    CHECK (language_level IS NULL OR language_level IN ('A1', 'A2', 'B1', 'B2', 'C1'));

UPDATE students SET language_level = 'A1'
WHERE site_type = 'languages' AND language_level IS NULL;

CREATE TABLE IF NOT EXISTS language_topics (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language TEXT NOT NULL CHECK (language IN ('fr', 'ru')),
  level TEXT NOT NULL CHECK (level IN ('A1', 'A2', 'B1', 'B2', 'C1')),
  section TEXT NOT NULL
    CHECK (section IN ('grammar', 'vocabulary', 'phonetics', 'reading', 'speaking')),
  title TEXT NOT NULL CHECK (length(title) <= 160),
  description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 2000),
  position INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS language_topics_course_idx
  ON language_topics (language, level, position, id);

CREATE TABLE IF NOT EXISTS language_topic_materials (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id INTEGER NOT NULL REFERENCES language_topics(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (length(name) <= 160),
  url TEXT NOT NULL CHECK (length(url) <= 2000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS language_topic_materials_topic_idx
  ON language_topic_materials (topic_id);

ALTER TABLE homeworks
  ADD COLUMN IF NOT EXISTS language_topic_id INTEGER
    REFERENCES language_topics(id) ON DELETE SET NULL;

ALTER TABLE lessons
