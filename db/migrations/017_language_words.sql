CREATE TABLE IF NOT EXISTS language_topic_words (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id INTEGER NOT NULL REFERENCES language_topics(id) ON DELETE CASCADE,
  term TEXT NOT NULL CHECK (length(term) BETWEEN 1 AND 160),
  translation TEXT NOT NULL CHECK (length(translation) BETWEEN 1 AND 160),
  example TEXT NOT NULL DEFAULT '' CHECK (length(example) <= 300),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS language_topic_words_topic_idx
  ON language_topic_words (topic_id, id);
